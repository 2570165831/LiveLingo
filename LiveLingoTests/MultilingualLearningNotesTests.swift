import Foundation
import XCTest
@testable import LiveLingo

@MainActor
final class MultilingualLearningNotesTests: XCTestCase {
    private var englishEvidence: [TranscriptSegment] {
        [TranscriptSegment(startTime: 0, endTime: 2, english: "Ice is cold. Water flows.", chinese: "冰很冷。水会流动。"),
         TranscriptSegment(startTime: 2, endTime: 3, english: "Heat moves.", chinese: "热会传递。")]
    }

    private func batch(_ evidence: [TranscriptSegment]) -> LearningNoteBatch {
        LearningNoteBatch(id: UUID(), evidence: evidence,
            note: LearningNote(topic: "Heat", points: [LearningPoint(kind: "核心结论", text: "热会传递。",
                sources: [.init(index: 1, quote: "热会传递。")])]))
    }

    // Frozen on b614a3c before changing the production paths. These literals
    // must not be regenerated by the implementation being tested.
    func testEnglishLearningInputsAndDigestsMatchFrozenStep6Bytes() throws {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys]
        let expectedUnits = #"[{"id":"en0s0","index":0,"language":"en","text":"Ice is cold."},{"id":"en0s1","index":0,"language":"en","text":"Water flows."},{"id":"zh0s0","index":0,"language":"zh","text":"冰很冷。"},{"id":"zh0s1","index":0,"language":"zh","text":"水会流动。"},{"id":"en1s0","index":1,"language":"en","text":"Heat moves."},{"id":"zh1s0","index":1,"language":"zh","text":"热会传递。"}]"#
        XCTAssertTrue(try encoder.encode(LearningSourceUnit.make(englishEvidence)) == Data(expectedUnits.utf8))
        let expectedGeneration = #"{"evidence":[{"id":"en0s0","index":0,"language":"en","text":"Ice is cold."},{"id":"en0s1","index":0,"language":"en","text":"Water flows."},{"id":"zh0s0","index":0,"language":"zh","text":"冰很冷。"},{"id":"zh0s1","index":0,"language":"zh","text":"水会流动。"},{"id":"en1s0","index":1,"language":"en","text":"Heat moves."},{"id":"zh1s0","index":1,"language":"zh","text":"热会传递。"}],"pendingPoints":[]}"#
        XCTAssertTrue(Data(try LearningPrompts.input(evidence: englishEvidence, topics: []).utf8)
            == Data(expectedGeneration.utf8))
        let expectedReview = #"{"evidence":[{"index":0,"quotes":[{"id":"e0.en.0","language":"en","text":"Ice is cold. Water flows."},{"id":"e0.zh.0","language":"zh","text":"冰很冷。水会流动。"}]},{"index":1,"quotes":[{"id":"e1.en.0","language":"en","text":"Heat moves."},{"id":"e1.zh.0","language":"zh","text":"热会传递。"}]}],"laterContext":[],"laterEvidence":[],"laterEvidenceOmittedCount":0,"note":{"points":[{"index":0,"kind":"核心结论","sources":[{"index":1,"quote":"热会传递。"}],"text":"热会传递。"}],"topic":"Heat"},"omittedEarlierCandidates":0,"reviewVersion":2}"#
        let prepared = try LearningPrompts.reviewInput(batch(englishEvidence))
        XCTAssertTrue(Data(prepared.json.utf8) == Data(expectedReview.utf8))
        XCTAssertEqual(SessionArchiveCoding.digest(Data(LearningPrompts.generate.utf8)),
            "b7429da5ca0fff3d4817ffaefcc05991186f90026a567d42c7092ec91cfb5d38")
        XCTAssertEqual(SessionArchiveCoding.digest(Data(LearningPrompts.review.utf8)),
            "ab5bce580c7f4ba53cb7ac419e51dbfdcf1517315e0869cc16272ae8fd916fcd")
        XCTAssertEqual(LearningReviewQueue.prefixDigest(json: prepared.json, prompt: LearningPrompts.review),
            "52b48a1e6e90e950d7b93cb2484921d5d5f667e5c47ea57374514ac64978f085")
    }

    func testEnglishSummaryMatchesFrozenStep6Bytes() {
        let expected = """
